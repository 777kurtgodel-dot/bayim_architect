export type SeedResult = { skipped: boolean; message: string; adminCreated?: string }

const context: RequestContext = { disableRevalidate: true, skipNotify: true }

const imagesDir = () => {
  const candidates = [path.resolve(process.cwd(), 'src/seed/images'), path.resolve(process.cwd(), 'seed/images')]
  const dir = candidates.find((d) => fs.existsSync(d))
  if (!dir) throw new Error(`Не найдена папка с демо-изображениями (${candidates.join(', ')})`)
  return dir
}

